    mlp = BaselineMLP(input_dim=Xtr_flat.shape[1], hidden=128, out_dim=2)
    acc_mlp = train_baseline(mlp, train_mlp, val_mlp, epochs=EPOCHS_SMALL, lr=LR, device=DEVICE, regression=False)

    # QDMN variant: register modules on flattened dim
    DIM = Xtr_flat.shape[1]
    qdmn_img = QDMN(initial_dim=DIM)
    # F, B preserve dim; U compress to 32, D reconstruct; H head maps to logits
    qdmn_img.register_module('F', LinearBlock(DIM, DIM, act=nn.ReLU), in_dim=DIM, out_dim=DIM)
    qdmn_img.register_module('B', LinearBlock(DIM, DIM, act=nn.Tanh), in_dim=DIM, out_dim=DIM)
    qdmn_img.register_module('U', LinearBlock(DIM, 32, act=nn.ReLU), in_dim=DIM, out_dim=32)
    qdmn_img.register_module('F', LinearBlock(32, 32, act=nn.ReLU), in_dim=32, out_dim=32)
    qdmn_img.register_module('D', LinearBlock(32, DIM, act=nn.ReLU), in_dim=32, out_dim=DIM)
    qdmn_img.register_module('H', nn.Linear(DIM, 2), in_dim=DIM, out_dim=2)  # classifier head
    # Train QDMN on route ['F','H'] (short) and evaluate also on ['U','D','H']
    acc_q_short = train_qdmn(qdmn_img, ['F','H'], train_mlp, val_mlp, epochs=EPOCHS_SMALL, lr=LR, device=DEVICE, regression=False)
    acc_q_comp = train_qdmn(qdmn_img, ['U','D','H'], train_mlp, val_mlp, epochs=EPOCHS_SMALL, lr=LR, device=DEVICE, regression=False)

