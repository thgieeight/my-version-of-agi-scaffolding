def fit_baseline_with_curves(model, train_loader, val_loader, epochs, lr=LR, device=DEVICE, verbose=False):
    model.to(device)
    opt = optim.Adam(model.parameters(), lr=lr)
    loss_fn = nn.MSELoss()
    train_losses = []; val_losses = []
    for ep in range(epochs):
        model.train()
        running = 0.0; cnt=0
        for xb,yb in train_loader:
            xb,yb = xb.to(device), yb.to(device)
            opt.zero_grad(); out = model(xb); loss = loss_fn(out,yb)
            loss.backward(); opt.step()
            running += loss.item()*xb.size(0); cnt += xb.size(0)
        train_losses.append(running/cnt if cnt>0 else 0.0)
        model.eval(); vr=0.0; vc=0
        with torch.no_grad():
            for xb,yb in val_loader:
                xb,yb = xb.to(device), yb.to(device)
                pred = model(xb)
                vr += ((pred-yb)**2).sum().item(); vc += yb.numel()
        val_losses.append(vr/vc if vc>0 else 0.0)
        if verbose and (ep+1)%50==0:
            print(f" baseline epoch {ep+1}/{epochs} train {train_losses[-1]:.6f} val {val_losses[-1]:.6f}")
    return train_losses, val_losses

