def mean_ci(a:List[float], alpha=0.05):
    arr = np.array(a)
    m = arr.mean()
    s = arr.std(ddof=1) if len(arr)>1 else 0.0
    n = len(arr)
    if n<=1:
        return m, (0.0, 0.0)
    se = s / math.sqrt(n)
    z = stats.t.ppf(1-alpha/2, df=n-1) if SCIPY_OK else 1.96
    lo, hi = m - z*se, m + z*se
    return m, (lo, hi)

def paired_ttest(a:List[float], b:List[float]) -> Tuple[float,float]:
    if SCIPY_OK:
        t, p = stats.ttest_rel(a,b)
        return float(t), float(p)
    a = np.array(a); b = np.array(b)
    d = a - b
    n = len(d)
    md = d.mean(); sd = d.std(ddof=1) if n>1 else 0.0
    se = sd / math.sqrt(n) if n>1 else 1e-12
    t = md / (se + 1e-12)
    return float(t), float('nan')

