class BaselineMLP(nn.Module):
    def __init__(self, input_dim:int, hidden:int=128, out_dim:int=None):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden),
            nn.ReLU(),
            nn.Linear(hidden, out_dim if out_dim is not None else input_dim)
        )
    def forward(self, x): return self.net(x.view(x.size(0), -1))

class BaselineCNN(nn.Module):
    def __init__(self, in_channels:int, out_dim:int):
        super().__init__()
        self.net = ConvSmall(in_channels, out_dim)
    def forward(self, x): return self.net(x)

class BaselineRNN(nn.Module):
    def __init__(self, seq_len:int, in_dim:int, out_dim:int, hidden:int=64):
        super().__init__()
        self.net = RNNBlock(seq_len, in_dim, out_dim, hidden)
    def forward(self, x): return self.net(x)

