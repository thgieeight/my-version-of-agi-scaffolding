def make_image_dataset(n_samples=1000, img_size=8):
    X = np.zeros((n_samples, 1, img_size, img_size), dtype=np.float32)
    y = np.zeros(n_samples, dtype=np.int64)
    for i in range(n_samples):
        cls = np.random.randint(0,2)
        y[i] = cls
        img = np.zeros((img_size, img_size), dtype=np.float32)
        if cls == 0:
            img[1:4,1:4] = 1.0
        else:
            img[4:7,4:7] = 1.0
        img += np.random.normal(0, 0.05, size=img.shape)
        X[i,0] = img
    return X, y

def make_sine_regression(n_samples=1000):
    X = np.random.uniform(-1, 1, size=(n_samples,1)).astype(np.float32)
    y = (np.sin(2*np.pi*X[:,0]) + np.random.normal(0, 0.1, size=n_samples)).astype(np.float32).reshape(-1,1)
    return X, y

def make_sequence_parity(n_samples=1000, seq_len=10):
    X = np.random.randint(0,2,size=(n_samples, seq_len)).astype(np.float32)
    y = (X.sum(axis=1) % 2).astype(np.int64)
    return X, y

