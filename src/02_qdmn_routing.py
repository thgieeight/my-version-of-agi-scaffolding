class ContractiveRefiner(nn.Module):
    """
    Spectrally-normalized, gated residual refiner
    Guarantees bounded iteration
    """
    def __init__(self, dim):
        super().__init__()
        self.W = nn.utils.parametrizations.spectral_norm(
            nn.Linear(dim, dim)
        )
        self.gate = nn.Linear(dim, 1)
        self.alpha = 0.1

    def forward(self, x):
        g = torch.sigmoid(self.gate(x))
        delta = torch.tanh(self.W(x))
        return x + self.alpha * g * delta

