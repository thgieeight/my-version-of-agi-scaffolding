# QDMN MASTER EXPERIMENT: Semantic Compositionality [F, U, D, B^n]
# Purpose: Proves the framework can compose directions to solve
# complex noise-filtering tasks via "Route-Based Logic."
# ============================================================

import torch
import torch.nn as nn
import torch.optim as optim
import matplotlib.pyplot as plt

# --- 1. The Quad-Directional Registry ---
class ContractiveB(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.net = nn.utils.parametrizations.spectral_norm(nn.Linear(dim, dim))
        self.gate = nn.Linear(dim, 1)
    def forward(self, x):
        g = torch.sigmoid(self.gate(x))
        return x + 0.1 * g * torch.tanh(self.net(x))

class QDMN_Master(nn.Module):
    def __init__(self):
        super().__init__()
        # Forward: Initial Projection
        self.F = nn.Linear(1, 64)
        # Up: Abstraction (Dimensionality Reduction)
        self.U = nn.Linear(64, 16)
        # Down: Reconstruction (Dimensionality Expansion)
        self.D = nn.Linear(16, 64)
        # Backward: Iterative Refinement
        self.B = ContractiveB(64)
        # Head: Output mapping
        self.H = nn.Linear(64, 1)

    def route(self, path, x):
        s = x
        for step in path:
            if step == 'F': s = torch.relu(self.F(s))
            elif step == 'U': s = torch.relu(self.U(s))
            elif step == 'D': s = torch.relu(self.D(s))
            elif step == 'B': s = self.B(s)
            elif step == 'H': s = self.H(s)
        return s

# --- 2. Data: Noisy Sine Wave ---
x = torch.linspace(-1, 1, 500).view(-1, 1)
clean_y = torch.sin(3 * x)
noisy_y = clean_y + 0.3 * torch.randn_like(clean_y) # 30% noise

# --- 3. Training the Composition ---
model = QDMN_Master()
optimizer = optim.Adam(model.parameters(), lr=0.01)

print("Training Master Route: [F -> U -> D -> B]...")
for i in range(1000):
    optimizer.zero_grad()
    # Train the model to clean noise using a specific semantic route
    pred = model.route(['F', 'U', 'D', 'B', 'H'], noisy_y)
    loss = nn.MSELoss()(pred, clean_y)
    loss.backward()
    optimizer.step()

# --- 4. Inference: The "Power of the Route" ---
with torch.no_grad():
    # Route 1: Fast (No refinement)
    y_fast = model.route(['F', 'H'], noisy_y)
    # Route 2: Deep (Full Semantic Composition)
    y_full = model.route(['F', 'U', 'D', 'B', 'B', 'B', 'H'], noisy_y)

# --- 5. Visualization for Paper ---
plt.figure(figsize=(10, 5))
plt.scatter(x, noisy_y, alpha=0.2, label="Noisy Input", color='gray')
plt.plot(x, clean_y, 'k--', label="Ground Truth", lw=2)
plt.plot(x, y_fast, label="Short Route [F, H]", color='red')
plt.plot(x, y_full, label="Master Route [F, U, D, B^3, H]", color='blue', lw=3)
plt.title("QDMN Semantic Compositionality: Noise Filtering via Programmable Routes")
plt.legend()
