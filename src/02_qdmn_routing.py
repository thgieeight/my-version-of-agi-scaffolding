class CoreNode(nn.Module):
    def __init__(self, initial_dim: int):
        super().__init__()
        self._state: Optional[torch.Tensor] = None
        self._dim = initial_dim

    def set(self, x: torch.Tensor):
        if x.shape[-1] != self._dim and self._state is None:
            # allow initial state to set dim if created differently, but prefer consistent initial_dim
            self._dim = x.shape[-1]
        self._state = x
        self._dim = x.shape[-1]

    def get(self) -> torch.Tensor:
        if self._state is None:
            raise RuntimeError("CoreNode empty: call set(x) first")
        return self._state

    @property
    def dim(self) -> int:
        return self._dim

class ModuleSpec:
    def __init__(self, name: str, module: nn.Module, in_dim: int, out_dim: int):
        self.name = name
        self.module = module
        self.in_dim = in_dim
        self.out_dim = out_dim

class QDMN(nn.Module):
    def __init__(self, initial_dim: int):
        super().__init__()
        self.core = CoreNode(initial_dim)
        self.initial_dim = initial_dim
        # registry: in_dim -> {symbol -> ModuleSpec}
        self._registry: Dict[int, Dict[str, ModuleSpec]] = {}

    def register_module(self, name: str, module: nn.Module, in_dim: int, out_dim: int, replace: bool=False):
        if in_dim not in self._registry:
            self._registry[in_dim] = {}
        if name in self._registry[in_dim] and not replace:
            raise KeyError(f"Module for ({name}, in_dim={in_dim}) already registered")
        self._registry[in_dim][name] = ModuleSpec(name, module, in_dim, out_dim)
        # register submodule for PyTorch tracking
        self.add_module(f"mod_{name}_{in_dim}", module)

    def _find_module_for_step(self, step: str, cur_dim: int) -> ModuleSpec:
        if cur_dim not in self._registry:
            raise RuntimeError(f"No modules registered for current dim {cur_dim}")
        if step not in self._registry[cur_dim]:
            raise RuntimeError(f"Module '{step}' not registered for dim {cur_dim}")
        return self._registry[cur_dim][step]

    def route(self, path: List[str], x: torch.Tensor, verbose: bool=False) -> torch.Tensor:
        # x shape (..., feature_dim)
        if self.core._state is None:  # allow core to accept this first input
            self.core.set(x)
        else:
            # require input last-dim to match initial dim for reproducibility
            if x.shape[-1] != self.initial_dim:
                # allow but warn
                pass
            self.core.set(x)

        if verbose:
            print(f"QDMN.route start dim={self.core.dim}, path={'->'.join(path)}")
        for i, step in enumerate(path):
            cur_dim = self.core.dim
            spec = self._find_module_for_step(step, cur_dim)
            out = spec.module(self.core.get())
            if out.shape[-1] != spec.out_dim:
                raise RuntimeError(f"Module '{step}' returned dim {out.shape[-1]} but expected {spec.out_dim}")
            self.core.set(out)
            if verbose:
                print(f" step {i+1}/{len(path)}: {step} ({spec.in_dim}->{spec.out_dim})")
        if verbose:
            print("QDMN.route finished, final dim=", self.core.dim)
        return self.core.get()

