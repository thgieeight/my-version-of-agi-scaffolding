    cnn = BaselineCNN(in_channels=1, out_dim=16)  # produce 16-d features
    # add final classifier head
    cnn_head = nn.Linear(16, 2)
    cnn_full = nn.Sequential(cnn, cnn_head)
    acc_cnn = train_baseline(cnn_full, train_cnn, val_cnn, epochs=EPOCHS_SMALL, lr=LR, device=DEVICE, regression=False)
    # Baseline MLP (flatten)
    Xtr_flat = Xtr.reshape(len(Xtr), -1); Xval_flat = Xval.reshape(len(Xval), -1)
