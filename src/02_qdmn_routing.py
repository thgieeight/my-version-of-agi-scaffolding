def top_singular_power(W:torch.Tensor, iters=50):
    device = W.device
    u = torch.randn((W.size(0),1), device=device)
    for _ in range(iters):
        v = W.t().matmul(u)
        v = v / (v.norm()+1e-12)
        u = W.matmul(v)
        u = u / (u.norm()+1e-12)
    sigma = (u.t().matmul(W.matmul(v))).item()
    return abs(sigma)

def compute_grad_norms_wrt_state(model:QDMNModel, Xb:torch.Tensor, Yb:torch.Tensor, depth:int, device=DEVICE):
    model.to(device); model.eval()
    Xb = Xb.to(device); Yb = Yb.to(device)
    out, states = model(Xb, depth=depth, return_states=True)
    s = states[-1]
    s_var = s.detach().clone().requires_grad_(True)
    pred = model.D(s_var)
    loss = nn.MSELoss()(pred, Yb)
    loss.backward()
    grad_norm = s_var.grad.norm().item()
    return float(grad_norm)

