# =================================================================
# 1. THE CORE FRAMEWORK (Architecture-First)
# =================================================================
class QDMN_Fabric(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.dim = dim
        self.registry = nn.ModuleDict()

    def register(self, direction, module):
        self.registry[direction] = module

    def route(self, path, x):
        state = x
        for step in path:
            # FRAMEWORK LOGIC: Apply the semantic module
            state = self.registry[step](state)
        return state

# =================================================================
# 2. SEMANTIC MODULES (The "Instructions")
# =================================================================
class Refiner(nn.Module):
    """A 'B' module that uses residual logic for stability."""
    def __init__(self, dim):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(dim, dim), nn.ReLU(), nn.Linear(dim, dim))
        self.alpha = nn.Parameter(torch.tensor([0.1])) # Control influence

    def forward(self, x):
        # REFINEMENT: Only change the state slightly (Stability)
        return x + self.alpha * torch.tanh(self.net(x))

