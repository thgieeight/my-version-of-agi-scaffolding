def count_params(m:nn.Module):
    return sum(p.numel() for p in m.parameters() if p.requires_grad)

def train_baseline(model, train_loader, val_loader, epochs, lr, device, regression=False, verbose=False):
    model.to(device)
    opt = optim.Adam(model.parameters(), lr=lr)
    loss_fn = nn.MSELoss() if regression else nn.CrossEntropyLoss()
    for ep in range(epochs):
        model.train()
        for xb, yb in train_loader:
            xb = xb.to(device); yb = yb.to(device)
            opt.zero_grad()
            out = model(xb)
            loss = loss_fn(out, yb)
            loss.backward(); opt.step()
        if verbose and (ep+1) % 20 == 0:
            print(f" epoch {ep+1}/{epochs} train loss {loss.item():.6f}")
    # eval
    model.eval()
    with torch.no_grad():
        total_loss = 0.0; total_count=0
        if regression:
            for xb,yb in val_loader:
                xb=xb.to(device); yb=yb.to(device)
                pred = model(xb)
                total_loss += ((pred-yb)**2).sum().item()
                total_count += yb.numel()
            return total_loss / total_count
        else:
            correct=0; total=0
            for xb,yb in val_loader:
                xb=xb.to(device); yb=yb.to(device)
                pred = model(xb).argmax(dim=1)
                correct += (pred==yb).sum().item(); total += xb.size(0)
            return correct/total

def train_qdmn(qdmn:QDMN, route:List[str], train_loader, val_loader, epochs, lr, device, regression=False, verbose=False):
    qdmn.to(device)
    opt = optim.Adam(qdmn.parameters(), lr=lr)
    loss_fn = nn.MSELoss() if regression else nn.CrossEntropyLoss()
    for ep in range(epochs):
        qdmn.train()
        for xb,yb in train_loader:
            xb=xb.to(device); yb=yb.to(device)
            opt.zero_grad()
            out = qdmn.route(route, xb, verbose=False)
            loss = loss_fn(out, yb)
            loss.backward(); opt.step()
        if verbose and (ep+1) % 20 == 0:
            print(f" epoch {ep+1}/{epochs} train loss {loss.item():.6f}")
    # eval
    qdmn.eval()
    with torch.no_grad():
        if regression:
            tot=0.0; cnt=0
            for xb,yb in val_loader:
                xb=xb.to(device); yb=yb.to(device)
                pred = qdmn.route(route, xb, verbose=False)
                tot += ((pred-yb)**2).sum().item(); cnt += yb.numel()
            return tot / cnt
        else:
            correct=0; tot=0
            for xb,yb in val_loader:
                xb=xb.to(device); yb=yb.to(device)
                pred = qdmn.route(route, xb, verbose=False).argmax(dim=1)
                correct += (pred==yb).sum().item(); tot += xb.size(0)
            return correct / tot

def measure_inference_time(model_callable, sample, runs=100, device=DEVICE):
    # model_callable: function that runs forward pass on sample (already on correct device)
    # returns avg ms per run
    with torch.no_grad():
        # warmup
        for _ in range(5):
            model_callable()
        t0 = time.time()
        for _ in range(runs):
            model_callable()
        t_total = time.time() - t0
    return (t_total / runs) * 1000.0

