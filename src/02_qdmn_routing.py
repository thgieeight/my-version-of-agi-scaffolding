class QDMNModel(nn.Module):
    def __init__(self, refiner:nn.Module, hidden=32):
        super().__init__()
        self.F = nn.Linear(1, hidden)
        self.B = refiner
        self.D = nn.Linear(hidden, 1)
        self.hidden = hidden
    def forward(self, x, depth=1, return_states=False):
        s = torch.relu(self.F(x.float()))
        states = [s]
        for _ in range(depth):
            s = self.B(s)
            states.append(s)
        out = self.D(s)
        if return_states:
            return out, states
        return out

