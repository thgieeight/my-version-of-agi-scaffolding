    novelty_flag = mse_long < mse_short

    results.append({
        'task': 'Novelty: route-switching (regression)',
        'metric': 'MSE (short vs long)',
        'mse_short': round(mse_short,6),
        'mse_long': round(mse_long,6),
        'novelty_improved': bool(novelty_flag)
    })
    print("Novelty test done. improved?:", novelty_flag)

    # Consolidate results
