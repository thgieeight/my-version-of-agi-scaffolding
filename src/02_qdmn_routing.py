class LinearBlock(nn.Module):
    def __init__(self, in_dim:int, out_dim:int, act:Optional[nn.Module]=nn.ReLU):
        super().__init__()
        self.lin = nn.Linear(in_dim, out_dim)
        self.act = act() if act is not None else nn.Identity()
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.act(self.lin(x))

class ConvSmall(nn.Module):
    """Simple conv backbone for tiny images; outputs flattened last-dim"""
    def __init__(self, in_channels:int, out_dim:int):
        super().__init__()
        # operate on (N, C, H, W) and output (N, out_dim) as last-dim feature
        self.net = nn.Sequential(
            nn.Conv2d(in_channels, 16, 3, padding=1), nn.ReLU(),
            nn.Conv2d(16, 32, 3, padding=1), nn.ReLU(),
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten(),
            nn.Linear(32, out_dim),
            nn.ReLU()
        )
    def forward(self, x):
        return self.net(x)

class RNNBlock(nn.Module):
    """Small RNN block that consumes last-dim as sequence length; wrapper for demonstration only."""
    def __init__(self, seq_len:int, in_dim:int, out_dim:int, hidden:int=64):
        super().__init__()
        self.seq_len = seq_len
        self.rnn = nn.LSTM(in_dim, hidden, batch_first=True)
        self.head = nn.Linear(hidden, out_dim)
    def forward(self, x):
        # x shape (N, seq_len*in_dim) or (N, seq_len, in_dim)
        if x.dim()==2:
            x = x.view(x.size(0), self.seq_len, -1)
        out, _ = self.rnn(x)
        return self.head(out[:, -1, :])

